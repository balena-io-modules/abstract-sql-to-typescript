import type {
	AbstractSqlField,
	AbstractSqlModel,
	AbstractSqlTable,
} from '@balena/abstract-sql-compiler';
import { expect } from 'chai';
import { source } from 'common-tags';
import { abstractSqlToTypescriptTypes, type Options } from '../src/generate.ts';
import packageJSON from '../package.json' with { type: 'json' };

export const test = (
	msg: string,
	model: Partial<AbstractSqlModel>,
	expectation: string,
	opts?: Options,
) => {
	it(`should generate ${msg}`, () => {
		// Set defaults for required props
		const t: AbstractSqlModel = {
			relationships: {},
			synonyms: {},
			tables: {},
			rules: [],
			lfInfo: { rules: {} },
			...model,
		};
		const result = abstractSqlToTypescriptTypes(t, opts);

		expect(result).to.equal(source`
			// These types were generated by @balena/abstract-sql-to-typescript v${packageJSON.version}

			import type { Types } from '@balena/abstract-sql-to-typescript';

			${expectation}
		`);
	});
};

export const idField: AbstractSqlField = {
	dataType: 'Serial',
	fieldName: 'id',
	required: true,
	index: 'PRIMARY KEY',
};

/**
 * Builds a table with the defaults that are irrelevant to most tests,
 * using the `resourceName` as the `name` unless one is provided
 */
export const table = (
	resourceName: string,
	fields: AbstractSqlField[],
	extra?: Partial<AbstractSqlTable>,
): AbstractSqlTable => ({
	name: resourceName,
	resourceName,
	idField: 'id',
	primitive: false,
	indexes: [],
	fields,
	...extra,
});
